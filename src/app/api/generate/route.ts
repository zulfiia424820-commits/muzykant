import { NextRequest, NextResponse } from 'next/server';
import Groq from 'groq-sdk';

type TabKey = 'scenario' | 'lesson' | 'song' | 'game';
type Payload = Record<string, string>;

const client = new Groq({ apiKey: process.env.GROQ_API_KEY });

const buildPrompt = (type: TabKey, values: Payload): string => {
  if (type === 'scenario') {
    return `Ты опытный музыкальный руководитель детского сада с 20-летним стажем.
Создай подробный сценарий утренника на тему "${values.theme ?? 'Праздник'}" для детей ${values.ageGroup ?? '3-5 лет'}.
Продолжительность: ${values.duration ?? '15'} минут. Размер группы: ${values.groupSize ?? '20'} детей.

Обязательно включи:
- Точный хронометраж каждого блока (например: 0:00 — Встреча гостей)
- 3-4 конкретные НАСТОЯЩИЕ песни из советского или современного репертуара с названиями, подходящие по теме и возрасту
- 2-3 музыкальные игры с ПОЛНЫМИ правилами, адаптированными под возраст
- Живой тёплый текст ведущего для каждого блока (не сухо, а как говорят с детьми)
- Список реквизита в конце

Пиши по-русски, живо и тепло. Формат: нумерованный план с временными метками.`;
  }

  if (type === 'lesson') {
    return `Ты опытный музыкальный руководитель детского сада.
Составь подробный план музыкального занятия на тему "${values.subject ?? 'Музыкальные игры'}" для детей.
Цели: ${values.goals ?? 'Развитие ритма и слуха'}.
Продолжительность: ${values.duration ?? '20'} минут.
Материалы: ${values.materials ?? 'барабаны, маракасы'}.

Включи:
- Приветственный ритуал с конкретным названием песни или игры
- Разминку с описанием движений
- Основную часть с пошаговыми упражнениями и названиями используемых песен
- Завершающий ритуал
- Хронометраж каждого блока
- Советы для воспитателя (что может пойти не так и как исправить)

Пиши по-русски, практично и понятно.`;
  }

  if (type === 'song') {
    return `Ты опытный музыкальный руководитель и автор детских песен.
Напиши оригинальную детскую песню или речёвку с названием "${values.title ?? 'Весёлая песенка'}".
Настроение: ${values.mood ?? 'Весёлое'}.
Подсказка: ${values.lyricsHint ?? 'Короткая контактная песенка с движениями'}.
Продолжительность исполнения: ${values.duration ?? '5'} минут.

Включи:
- Куплет 1 (4-8 строк, простые слова для детей)
- Припев (запоминающийся, ритмичный)
- Куплет 2
- Описание движений к каждой части (что делают руки, ноги, тело)
- Темп и характер исполнения
- На какой известный мотив можно петь (если подходит)

Слова простые, ритм чёткий, детям должно быть весело.`;
  }

  if (type === 'game') {
    return `Ты опытный музыкальный руководитель детского сада.
Опиши музыкальную игру "${values.name ?? 'Ритмическая игра'}" для ${values.participants ?? '10-30'} детей.
Цель: ${values.objective ?? 'Развитие внимания и координации'}.
Оборудование: ${values.equipment ?? 'минимальное'}.

Включи:
- Цель игры (для детей, простыми словами)
- Подготовка (как расставить детей, что объяснить заранее)
- Правила пошагово (как объяснить детям, не взрослым)
- Ход игры с примером первого раунда
- Музыкальное сопровождение (какая музыка или ритм подойдёт, конкретные примеры)
- Вариант для малышей (упрощение)
- Вариант посложнее (для старших или повтора)
- Как завершить игру красиво

Пиши живо, с примерами реплик ведущего.`;
  }

  return 'Выберите тип и заполните параметры.';
};

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const type = body.type as TabKey;
    const payload: Payload = body.payload ?? body.params ?? {};

    if (!process.env.GROQ_API_KEY) {
      return NextResponse.json(
        { error: 'GROQ_API_KEY не настроен в .env.local' },
        { status: 500 }
      );
    }

    const prompt = buildPrompt(type, payload);

    const completion = await client.chat.completions.create({
      model: 'llama-3.3-70b-versatile',
      messages: [{ role: 'user', content: prompt }],
      temperature: 0.8,
      max_tokens: 2048,
    });

    const content = completion.choices[0]?.message?.content ?? 'Не удалось сгенерировать контент.';
    return NextResponse.json({ content });

  } catch (error: any) {
    console.error('Groq error:', error);
    return NextResponse.json(
      { error: `Ошибка генерации: ${error?.message ?? 'неизвестная ошибка'}` },
      { status: 500 }
    );
  }
}
